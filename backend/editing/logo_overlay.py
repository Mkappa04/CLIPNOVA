"""Brand Kit logo: upload validation/storage, settings and deterministic FFmpeg overlay geometry.

The logo is never placed by AI: position/size/opacity come from the Brand Kit settings and are applied
by FFmpeg ``overlay``. Uploaded files are decoded and re-encoded with OpenCV (drops metadata and any
non-image payload), stored under ``data/brand`` with a random name, and served only through the API.
"""

from __future__ import annotations

import secrets
import struct
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import cv2
import numpy as np
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.automation.common import get_setting, put_setting
from backend.core.config import get_settings
from backend.core.exceptions import ValidationFailed
from backend.editing.config import OUT_H, OUT_W
from backend.models.entities import BrandAsset

PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
SETTINGS_KEY = "brand_kit"
OWNER = "local"  # single local profile (CLIPNOVA runs on your PC); kept as a column for future accounts

Corner = Literal["top-right", "top-left", "bottom-right", "bottom-left"]

# Approximate platform UI zones on 1080x1920 (TikTok / Reels / Shorts): status bar + tabs on top,
# caption/username at the bottom, action buttons on the lower right.
SAFE_TOP = 190
SAFE_BOTTOM = 380
SAFE_SIDE = 36
SAFE_RIGHT_BUTTONS = 150   # extra inset for bottom-right (like/comment/share column)


class BrandSettings(BaseModel):
    enabled: bool = True
    position: Corner = "top-right"
    size: float = Field(0.18, ge=0.05, le=0.4, description="Logo width as a fraction of the video width")
    opacity: float = Field(0.85, ge=0.1, le=1.0)
    margin: int = Field(40, ge=0, le=200, description="Distance from the edges (px on 1080x1920)")
    safe_area: bool = Field(True, description="Keep the logo out of the platforms' UI zones")


def load_settings(db: Session) -> BrandSettings:
    return BrandSettings.model_validate(get_setting(db, SETTINGS_KEY, BrandSettings().model_dump()))


def save_settings(db: Session, s: BrandSettings) -> BrandSettings:
    put_setting(db, SETTINGS_KEY, s.model_dump())
    db.commit()
    return s


def current_logo(db: Session) -> BrandAsset | None:
    return db.scalars(select(BrandAsset).where(BrandAsset.owner == OWNER, BrandAsset.kind == "logo")
                      .order_by(BrandAsset.created_at.desc())).first()


def logo_path(asset: BrandAsset) -> Path:
    root = get_settings().brand_dir.resolve()
    p = (root / asset.stored_name).resolve()
    if p.parent != root:  # stored_name is generated by us, but never trust a path from the DB blindly
        raise ValidationFailed("Invalid logo path")
    return p


def _png_header_size(data: bytes) -> tuple[int, int]:
    """Width/height from the IHDR chunk, read *before* decoding (decompression-bomb guard)."""
    if len(data) < 33 or data[12:16] != b"IHDR":
        raise ValidationFailed("PNG non valido (manca l'header IHDR)", code="invalid_logo")
    return struct.unpack(">II", data[16:24])


def validate_png(data: bytes, filename: str) -> tuple[np.ndarray, list[str]]:
    """Validated logo as a BGRA uint8 array (transparent borders trimmed) + warnings."""
    s = get_settings()
    warnings: list[str] = []
    max_bytes = int(s.brand_logo_max_mb * 1024 * 1024)
    if not data:
        raise ValidationFailed("File vuoto", code="invalid_logo")
    if len(data) > max_bytes:
        raise ValidationFailed(f"Logo troppo grande ({len(data) / 1e6:.1f} MB, massimo {s.brand_logo_max_mb:g} MB)",
                               code="logo_too_large")
    if not data.startswith(PNG_MAGIC):
        raise ValidationFailed("Il logo deve essere un file PNG", code="invalid_logo")
    w, h = _png_header_size(data)
    if w < 16 or h < 16:
        raise ValidationFailed("Logo troppo piccolo (minimo 16×16 px)", code="invalid_logo")
    if w > s.brand_logo_max_px or h > s.brand_logo_max_px:
        raise ValidationFailed(f"Logo troppo grande ({w}×{h}, massimo {s.brand_logo_max_px} px per lato)",
                               code="invalid_logo")
    img = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_UNCHANGED)
    if img is None or img.shape[0] != h or img.shape[1] != w:
        raise ValidationFailed("PNG non valido o danneggiato", code="invalid_logo")
    if img.dtype == np.uint16:
        img = (img / 257).astype(np.uint8)
    has_alpha = img.ndim == 3 and img.shape[2] == 4
    if img.ndim == 2:
        img = cv2.cvtColor(img, cv2.COLOR_GRAY2BGRA)
    elif img.shape[2] == 3:
        img = cv2.cvtColor(img, cv2.COLOR_BGR2BGRA)
    alpha = img[:, :, 3]
    if not has_alpha:
        warnings.append("Il PNG non ha trasparenza: il logo verrà mostrato con il suo sfondo")
    elif int(alpha.min()) == 255:
        warnings.append("Il PNG ha il canale alfa ma nessun pixel trasparente")
    ys, xs = np.nonzero(alpha)
    if len(xs) == 0:
        raise ValidationFailed("Il logo è completamente trasparente", code="invalid_logo")
    x0, x1, y0, y1 = int(xs.min()), int(xs.max()) + 1, int(ys.min()), int(ys.max()) + 1
    if (x1 - x0, y1 - y0) != (w, h):  # trim fully transparent borders: size/margins refer to the visible logo
        img = img[y0:y1, x0:x1]
    return np.ascontiguousarray(img), warnings


def store_logo(db: Session, data: bytes, filename: str) -> tuple[BrandAsset, list[str]]:
    img, warnings = validate_png(data, filename)
    d = get_settings().brand_dir
    d.mkdir(parents=True, exist_ok=True)
    name = f"logo_{secrets.token_hex(8)}.png"
    out = d / name
    ok, buf = cv2.imencode(".png", img, [cv2.IMWRITE_PNG_COMPRESSION, 6])  # re-encoded: metadata dropped
    if not ok:
        raise ValidationFailed("Impossibile salvare il logo", code="invalid_logo")
    out.write_bytes(buf.tobytes())
    has_alpha = not any("non ha trasparenza" in w for w in warnings)
    old = current_logo(db)
    asset = BrandAsset(owner=OWNER, kind="logo", original_name=Path(filename or "logo.png").name[:255],
                       stored_name=name, width=int(img.shape[1]), height=int(img.shape[0]),
                       file_size=out.stat().st_size, has_alpha=has_alpha)
    db.add(asset)
    if old is not None:  # replace: one logo per profile
        delete_asset(db, old)
    db.commit()
    db.refresh(asset)
    return asset, warnings


def delete_asset(db: Session, asset: BrandAsset) -> None:
    try:
        logo_path(asset).unlink(missing_ok=True)
    except ValidationFailed:
        pass
    db.delete(asset)


# ------------------------------------------------------------------ geometry
@dataclass
class LogoPlacement:
    path: Path
    x: int
    y: int
    w: int
    h: int
    opacity: float
    corner: str
    warnings: list[str]


def place(asset_w: int, asset_h: int, s: BrandSettings, *, subtitle_position: str = "bottom",
          subtitles: bool = True, pip_corner: str | None = None) -> tuple[int, int, int, int, str, list[str]]:
    """(x, y, w, h, corner, warnings) on the 1080x1920 frame. Aspect ratio always preserved."""
    warnings: list[str] = []
    w = max(16, int(OUT_W * s.size) // 2 * 2)
    h = int(round(w * asset_h / asset_w)) // 2 * 2
    max_h = int(OUT_H * 0.16)
    if h > max_h:  # very tall logos: limit the height, keep the aspect
        h = max_h // 2 * 2
        w = int(round(h * asset_w / asset_h)) // 2 * 2
    corner = s.position
    if pip_corner and pip_corner == corner:
        corner = corner.replace("left", "@").replace("right", "left").replace("@", "right")
        warnings.append(f"Logo spostato in {corner}: l'angolo scelto è occupato dalla webcam (PiP)")
    if subtitles and subtitle_position == "top" and corner.startswith("top"):
        corner = corner.replace("top", "bottom")
        warnings.append(f"Logo spostato in {corner}: in alto ci sono i sottotitoli")
    side = SAFE_SIDE if s.safe_area else 0
    top = SAFE_TOP if s.safe_area else 0
    bottom = SAFE_BOTTOM if s.safe_area else 0
    right_extra = SAFE_RIGHT_BUTTONS if (s.safe_area and corner == "bottom-right") else 0
    x = s.margin + side if "left" in corner else OUT_W - w - s.margin - side - right_extra
    y = s.margin + top if corner.startswith("top") else OUT_H - h - s.margin - bottom
    x = max(0, min(OUT_W - w, x))
    y = max(0, min(OUT_H - h, y))
    return x, y, w, h, corner, warnings


def placement_for(db: Session, *, subtitle_position: str, subtitles: bool,
                  pip_corner: str | None) -> LogoPlacement | None:
    s = load_settings(db)
    asset = current_logo(db)
    if asset is None or not s.enabled:
        return None
    p = logo_path(asset)
    if not p.exists():
        return None
    x, y, w, h, corner, warnings = place(asset.width, asset.height, s, subtitle_position=subtitle_position,
                                         subtitles=subtitles, pip_corner=pip_corner)
    return LogoPlacement(p, x, y, w, h, s.opacity, corner, warnings)


def overlay_filter(logo_input: int, src_label: str, out_label: str, lp: LogoPlacement) -> str:
    """FFmpeg filter: scale with Lanczos to the exact box (aspect preserved by `place`), apply opacity on
    the alpha channel, overlay at integer coordinates. No paths in the filter string."""
    return (f"[{logo_input}:v]format=rgba,scale={lp.w}:{lp.h}:flags=lanczos,"
            f"colorchannelmixer=aa={lp.opacity:.3f}[logo];"
            f"[{src_label}][logo]overlay=x={lp.x}:y={lp.y}:format=auto:eof_action=repeat[{out_label}]")
